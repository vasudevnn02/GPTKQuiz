/**
 * Gets direct Twemoji CDN 2D Vector SVG URL for an avatar definition
 */
export function getAvatarTwemojiUrl(avatar) {
  if (!avatar || !avatar.codePoint) return null;
  return `https://cdn.jsdelivr.net/gh/twitter/twemoji@14.0.2/assets/svg/${avatar.codePoint}.svg`;
}

/**
 * Finds avatar by ID or returns default
 */
export function getAvatarById(id) {
  if (!id) return AVATAR_DEFINITIONS[0];
  return AVATAR_DEFINITIONS.find(a => a.id === id) || AVATAR_DEFINITIONS[0];
}

/**
 * Gets student's saved avatar definition or deterministic fallback
 */
export function getSavedStudentAvatarDef(rollNo) {
  if (!rollNo) rollNo = 'student';
  const savedId = localStorage.getItem(`gptk_avatar_${rollNo}`);
  if (savedId) {
    const found = AVATAR_DEFINITIONS.find(a => a.id === savedId);
    if (found) return found;
  }
  const defaultIdx = (rollNo.charCodeAt(rollNo.length - 1) || 0) % AVATAR_DEFINITIONS.length;
  return AVATAR_DEFINITIONS[defaultIdx];
}

/**
 * Compatibility wrapper for existing callers expecting an image URL
 */
export function getSavedStudentAvatar(rollNo) {
  const def = getSavedStudentAvatarDef(rollNo);
  return getAvatarTwemojiUrl(def);
}

/**
 * Compatibility wrapper for existing callers
 */
export function getAvatar2DPng(avatar) {
  return getAvatarTwemojiUrl(avatar);
}

export function saveStudentAvatar(rollNo, avatarId) {
  if (!rollNo) rollNo = 'student';
  localStorage.setItem(`gptk_avatar_${rollNo}`, avatarId);
}
